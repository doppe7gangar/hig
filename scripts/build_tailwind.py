#!/usr/bin/env python3
"""Tailwind themes for the iOS kit, generated from its CSS variables.

Every utility points at a kit variable rather than copying its value, so
Tailwind classes follow the kit into Dark Mode and Increase Contrast the
way the kit's own components do, and a re-measured token reaches them
without a rebuild of the theme. The variable list is read from the kit's
CSS, so a token added there shows up here the next time this runs.

    python3 scripts/build_tailwind.py           # write both
    python3 scripts/build_tailwind.py --check   # exit 1 if either is stale

Writes, into .claude/skills/apple-ui-kit/tailwind/:
    theme.css   Tailwind v4:  @import "tailwindcss"; then this file
    preset.cjs  Tailwind v3:  presets: [require("./preset.cjs")]
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.join(os.path.dirname(HERE), ".claude", "skills", "apple-ui-kit")
SOURCES = [os.path.join(KIT, "tokens", "ios-tokens.css"), os.path.join(KIT, "ios-components.css")]
OUT = os.path.join(KIT, "tailwind")

NOT_COLOUR = re.compile(r"^(text|track|weight|font|radius|gutter|hit-target|disabled-opacity|"
                        r"stepper|switch|tab-pill)\b")


def variables():
    names = []
    for path in SOURCES:
        for name in re.findall(r"^\s*--ios-([a-z0-9-]+)\s*:", open(path, encoding="utf-8").read(), re.M):
            if name not in names:
                names.append(name)
    return names


def groups(names):
    colours = [n for n in names if not NOT_COLOUR.match(n)]
    text = [n[5:] for n in names if n.startswith("text-") and f"track-{n[5:]}" in names]
    radius = [n[7:] for n in names if n.startswith("radius-")]
    weights = [n[7:] for n in names if n.startswith("weight-")]
    return colours, text, radius, weights


HEADER = ("Generated by scripts/build_tailwind.py from the kit's CSS variables; "
          "do not hand-edit.")


def v4(names):
    colours, text, radius, weights = groups(names)
    out = [f"/* Tailwind v4 theme for the iOS kit. {HEADER}",
           "",
           "   Every utility reads a kit variable, so load the kit's tokens too;",
           "   colours then follow Dark Mode and Increase Contrast on their own:",
           "",
           '     @import "tailwindcss";',
           '     @import "./vendor/ios-tokens.css";',
           '     @import "./vendor/ios-components.css";   (for the components)',
           '     @import "./vendor/tailwind/theme.css";',
           "",
           "   bg-ios-accent, text-ios-label-secondary, rounded-ios-card, px-ios-gutter,",
           "   size-ios-hit (44pt), font-ios, font-ios-semibold, and ios-text-body",
           "   for a whole text style: size, line height, weight and tracking. */",
           "",
           "@theme inline {",
           "  --font-ios: var(--ios-font);"]
    out += [f"  --color-ios-{n}: var(--ios-{n});" for n in colours]
    out += [f"  --radius-ios-{n}: var(--ios-radius-{n});" for n in radius]
    out += [f"  --font-weight-ios-{n}: var(--ios-weight-{n});" for n in weights]
    out += ["  --spacing-ios-gutter: var(--ios-gutter);",
            "  --spacing-ios-hit: var(--ios-hit-target);",
            "}", ""]
    for n in text:
        out += [f"@utility ios-text-{n} {{",
                f"  font: var(--ios-text-{n});",
                f"  letter-spacing: var(--ios-track-{n});",
                "}"]
    return "\n".join(out) + "\n"


def v3(names):
    colours, text, radius, weights = groups(names)
    q = lambda s: f"'{s}'"
    out = [f"// Tailwind v3 preset for the iOS kit. {HEADER}",
           "//",
           "// Every utility reads a kit variable, so load the kit's tokens in your CSS",
           "// as well; colours then follow Dark Mode and Increase Contrast. Opacity",
           "// modifiers (bg-ios-accent/50) need v4: v3 can't apply them to a variable.",
           "//",
           "//   module.exports = { presets: [require('./vendor/tailwind/preset.cjs')], ... }",
           "",
           "module.exports = {",
           "  theme: {",
           "    extend: {",
           "      colors: {",
           "        ios: {"]
    out += [f"          {q(n)}: 'var(--ios-{n})'," for n in colours]
    out += ["        },",
            "      },",
            "      fontFamily: { ios: ['var(--ios-font)'] },",
            "      fontWeight: {"]
    out += [f"        {q('ios-' + n)}: 'var(--ios-weight-{n})'," for n in weights]
    out += ["      },",
            "      borderRadius: {"]
    out += [f"        {q('ios-' + n)}: 'var(--ios-radius-{n})'," for n in radius]
    out += ["      },",
            "      spacing: {",
            "        'ios-gutter': 'var(--ios-gutter)',",
            "        'ios-hit': 'var(--ios-hit-target)',",
            "      },",
            "    },",
            "  },",
            "  plugins: [",
            "    function ({ addUtilities }) {",
            "      addUtilities({"]
    out += [f"        '.ios-text-{n}': {{ font: 'var(--ios-text-{n})', "
            f"letterSpacing: 'var(--ios-track-{n})' }}," for n in text]
    out += ["      });",
            "    },",
            "  ],",
            "};"]
    return "\n".join(out) + "\n"


def main():
    names = variables()
    files = {"theme.css": v4(names), "preset.cjs": v3(names)}
    if "--check" in sys.argv:
        stale = [f for f, body in files.items()
                 if not os.path.exists(os.path.join(OUT, f))
                 or open(os.path.join(OUT, f), encoding="utf-8").read() != body]
        if stale:
            print("stale: " + ", ".join(stale) + "; run python3 scripts/build_tailwind.py")
            return 1
        print("tailwind themes are current")
        return 0
    os.makedirs(OUT, exist_ok=True)
    for f, body in files.items():
        with open(os.path.join(OUT, f), "w", encoding="utf-8") as fh:
            fh.write(body)
    colours, text, radius, weights = groups(names)
    print(f"{len(colours)} colours, {len(text)} text styles, {len(radius)} radii, "
          f"{len(weights)} weights -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
